export type TranslationKey = keyof typeof UI_TRANSLATIONS['ar'];

export function t(key: TranslationKey, lang: Language = 'ar'): string {
  const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.ar;
  return dictionary[key] || UI_TRANSLATIONS.ar[key] || key;
}

export function getProductName(product: Product, lang: Language): string {
  if (lang === 'en' && product.nameEn) return product.nameEn;
  if (lang === 'fr' && product.nameFr) return product.nameFr;
  if (lang === 'fr' && product.nameEn) return product.nameEn; // fallback
  return product.name;
}

export function getProductDescription(product: Product, lang: Language): string {
  if (lang === 'en' && product.descriptionEn) return product.descriptionEn;
  if (lang === 'fr' && product.descriptionFr) return product.descriptionFr;
  if (lang === 'fr' && product.descriptionEn) return product.descriptionEn;
  return product.description;
}

export function getProductBadge(product: Product, lang: Language): string | undefined {
  if (!product.badge) return undefined;
  if (lang === 'en') {
    if (product.badgeEn) return product.badgeEn;
    if (product.badge === 'الأكثر مبيعاً') return 'Best Seller';
    if (product.badge === 'توصية الذكاء الاصطناعي') return 'AI Recommended';
    if (product.badge === 'جديد الحزمة الثامنة') return 'Suite v8 New';
    if (product.badge === 'خصم حصري') return 'Exclusive Deal';
  }
  if (lang === 'fr') {
    if (product.badgeFr) return product.badgeFr;
    if (product.badge === 'الأكثر مبيعاً') return 'Meilleure Vente';
    if (product.badge === 'توصية الذكاء الاصطناعي') return 'Recommandé par IA';
    if (product.badge === 'جديد الحزمة الثامنة') return 'Nouveauté Suite v8';
    if (product.badge === 'خصم حصري') return 'Offre Exclusive';
  }
  return product.badge;
}

export function getProductSpecs(product: Product, lang: Language): Record<string, string> {
  if (lang === 'en' && product.specsEn) return product.specsEn;
  if (lang === 'fr' && product.specsFr) return product.specsFr;
  return product.specs;
}
